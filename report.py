# Week 2 Day 3 - 小项目②: 销售周报生成器
# 输入: 一周的脏跟进记录 (像不像你 CRM 导出来的东西)
# 输出: 一份能直接发老板的周报

import pandas as pd

# ---------- 第 1 步: 原始脏数据 (8 条, 有空格 / 大小写不一致) ----------

raw = [
    {"日期": "2026-08-31", "客户": "腾讯云", "动作": "电话", "金额": 120000},
    {"日期": "2026-08-31", "客户": "腾讯云", "动作": "演示", "金额": 0},
    {"日期": "2026-09-01", "客户": " 拼多多 ", "动作": "电话", "金额": 80000},
    {"日期": "2026-09-01", "客户": "拼多多", "动作": "报价", "金额": 0},
    {"日期": "2026-09-01", "客户": "美的", "动作": "电话", "金额": 95000},
    {"日期": "2026-09-02", "客户": "BYD", "动作": "拜访", "金额": 150000},
    {"日期": "2026-09-02", "客户": "byd", "动作": "报价", "金额": 0},
    {"日期": "2026-09-02", "客户": "顺丰", "动作": "电话", "金额": 60000},
]

df = pd.DataFrame(raw)
print("===== 原始记录 =====")
print(df)

# ---------- 第 2 步: 清洗 (复用 Day 2 学的 strip/lower 套路) ----------

df["客户"] = df["客户"].str.strip().str.lower()

# 内部统一小写后, 再把名字还原成正式展示名
name_map = {"byd": "比亚迪"}
df["客户"] = df["客户"].replace(name_map)

print()
print("===== 清洗后 (注意 BYD/byd 已合并成 比亚迪) =====")
print(df)

# ---------- 第 3 步: 汇总 - groupby 自动按客户合并 ----------

print()
print("===== 按客户汇总跟进次数与意向金额 =====")
summary = df.groupby("客户").agg(
    跟进次数=("客户", "count"),
    意向金额=("金额", "sum"),
)
print(summary)

print()
print("===== 按动作统计 =====")
print(df.groupby("动作").size())

# ---------- 第 4 步: 生成周报 ----------

print()
print("========================================")
print("           本周销售周报 (自动生成)")
print("========================================")
print(f"本周跟进客户: {df['客户'].nunique()} 家")
print(f"总跟进动作: {len(df)} 次")
print(f"新增意向金额: {df['金额'].sum()} 元")
top = df.groupby("客户")["金额"].sum().idxmax()
print(f"意向金额最高客户: {top}")
print("========================================")
