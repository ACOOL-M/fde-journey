import pandas as pd

# ---------- 第 1 关: DataFrame - 用代码造一张表格 ----------

records = [
    {"客户": "腾讯云", "金额": 120000, "状态": "已成交"},
    {"客户": "拼多多", "金额": 80000, "状态": "跟进中"},
    {"客户": "美的", "金额": 95000, "状态": "已成交"},
    {"客户": "比亚迪", "金额": 150000, "状态": "跟进中"},
    {"客户": "顺丰", "金额": 60000, "状态": "已成交"},
]

df = pd.DataFrame(records)
print("===== 完整表格 =====")
print(df)

# ---------- 第 2 关: 取列 / 筛选 ----------

print()
print("===== 只看金额这一列 =====")
print(df["金额"])

print()
print("===== 筛选: 已成交的客户 =====")
won = df[df["状态"] == "已成交"]
print(won)

print()
print("===== 筛选: 金额大于 90000 的客户 =====")
big = df[df["金额"] > 90000]
print(big)

# ---------- 第 3 关: 统计 - 一行代码顶手算一小时 ----------

print()
print("===== 统计 =====")
print("总金额:", df["金额"].sum())
print("平均金额:", df["金额"].mean())
print("最大单:", df["金额"].max())
print("客户数:", len(df))
print("已成交金额:", won["金额"].sum())
